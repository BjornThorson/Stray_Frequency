/**
 * Social simulation contracts. These represent beliefs held by a character,
 * not objective truth or player-visible friendship levels.
 */
export type SocialAxis =
  | 'familiarity'
  | 'warmth'
  | 'trust'
  | 'reliability'
  | 'respect'
  | 'discretion'
  | 'fear'
  | 'indebtedness';

export type SocialValues = Record<SocialAxis, number>;

export interface SocialRelationship extends SocialValues {
  /** The person holding this opinion. Direction matters. */
  observerId: string;
  /** The person this opinion concerns. */
  subjectId: string;
  lastPerceivedEventAt: string | null;
}

export interface SocialTraits {
  /** 0 = detached, 1 = strongly responsive to kindness. */
  empathy: number;
  /** 0 = trusting, 1 = cautious about new positive information. */
  scepticism: number;
}

export interface SocialProfile {
  id: string;
  traits: SocialTraits;
}

export type SocialEventKind =
  | 'conversation'
  | 'helped'
  | 'kept_promise'
  | 'broke_promise'
  | 'threatened';

export interface SocialEvent {
  /** Authoritative, stable event identifier, never generated by clients. */
  id: string;
  kind: SocialEventKind;
  actorId: string;
  targetId: string;
  occurredAt: string;
  locationId: string;
}

export interface SocialObservation {
  /** The character who knows about this particular event. */
  observerId: string;
  source: 'direct' | 'reported';
  /** Confidence in the information, from 0 to 1. */
  confidence: number;
}

export interface SocialState {
  /** Sparse, directional relationships. No record means no established opinion. */
  relationships: Record<string, SocialRelationship>;
  /**
   * Stage A idempotency ledger. Production persistence will replace this array
   * with a database uniqueness constraint on (event ID, observer ID).
   */
  processedObservations: string[];
}

export type SocialDelta = Partial<SocialValues>;
export interface SocialRule {
  /** What the actor may learn or feel towards the target. */
  actorToTarget: SocialDelta;
  /** What the target may learn or feel towards the actor. */
  targetToActor: SocialDelta;
  /** What a third-party witness may learn or feel towards the actor. */
  witnessToActor: SocialDelta;
}
